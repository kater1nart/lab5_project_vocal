from pathlib import Path

from pptx import Presentation
from pptx.dml.color import RGBColor
from pptx.util import Inches, Pt

HERE = Path(__file__).resolve().parent
prs = Presentation()
prs.slide_width, prs.slide_height = Inches(13.333), Inches(7.5)
BLANK = prs.slide_layouts[6]
FONT = "Arial"


def text(s, x, y, w, h, lines, size=20, bold_first=False):
    tf = s.shapes.add_textbox(Inches(x), Inches(y), Inches(w), Inches(h)).text_frame
    tf.word_wrap = True
    for i, ln in enumerate(lines):
        p = tf.paragraphs[0] if i == 0 else tf.add_paragraph()
        p.space_after = Pt(8)
        r = p.add_run(); r.text = ln
        r.font.name, r.font.size = FONT, Pt(size)
        r.font.color.rgb = RGBColor(0, 0, 0)
        r.font.bold = bold_first and i == 0


def slide(title):
    s = prs.slides.add_slide(BLANK)
    text(s, 0.6, 0.35, 12.1, 0.9, [title], size=28, bold_first=True)
    return s


def table(s, x, y, w, rows, col_w, size=13):
    t = s.shapes.add_table(len(rows), len(rows[0]), Inches(x), Inches(y), Inches(w), Inches(0.38 * len(rows))).table
    for i, r in enumerate(rows):
        for j, v in enumerate(r):
            c = t.cell(i, j); c.text = v
            for p in c.text_frame.paragraphs:
                for run in p.runs:
                    run.font.name, run.font.size, run.font.bold = FONT, Pt(size), i == 0
    for j, cw in enumerate(col_w):
        t.columns[j].width = Inches(cw)


def pic(s, f, x, y, w=None, h=None):
    kw = {}
    if w: kw["width"] = Inches(w)
    if h: kw["height"] = Inches(h)
    s.shapes.add_picture(str(HERE / f), Inches(x), Inches(y), **kw)


